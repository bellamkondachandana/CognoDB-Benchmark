from abc import ABC, abstractmethod

class GraphAdapter(ABC):
    name = "base"

    @abstractmethod
    def connect(self): ...
    @abstractmethod
    def close(self): ...
    @abstractmethod
    def reset(self): ...
    @abstractmethod
    def load_edges(self, edges, batch_size): ...
    @abstractmethod
    def one_hop(self, node): ...
    @abstractmethod
    def two_hop(self, node): ...
    @abstractmethod
    def three_hop(self, node): ...
    @abstractmethod
    def point_lookup(self, node): ...
    @abstractmethod
    def indexed_lookup(self, node): ...
    @abstractmethod
    def aggregation(self): ...
    @abstractmethod
    def mixed_read(self, node): ...
    @abstractmethod
    def mixed_write(self, src, dst, token): ...
    @abstractmethod
    def mixed_delete(self, token): ...
    @abstractmethod
    def footprint(self): ...
